/**
 * Stable launcher and copy-able MCP config. The launcher lives at `<home>/bin/openboard-mcp.js` and
 * requires the current extension's dist/mcp.js, so an extension update never breaks saved configs.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { binDir, ensurePrivateDir } from './instances';

export const LAUNCHER_NAME = 'openboard-mcp.js';

export const launcherPath = (home: string): string => path.join(binDir(home), LAUNCHER_NAME);

export function launcherSource(mcpEntry: string): string {
  return `'use strict';\n// Generated by the OpenBoard extension. Safe to delete; it is rewritten on activation.\nrequire(${JSON.stringify(mcpEntry)});\n`;
}

/** Writes the launcher when missing or pointing at a different entry. Returns its path. */
export function ensureLauncher(home: string, mcpEntry: string): string {
  const file = launcherPath(home);
  const source = launcherSource(mcpEntry);
  let current: string | undefined;
  try {
    current = readFileSync(file, 'utf8');
  } catch {
    current = undefined;
  }
  if (current !== source) {
    ensurePrivateDir(home);
    mkdirSync(binDir(home), { recursive: true });
    writeFileSync(file, source, { mode: 0o644 });
  }
  return file;
}

/** True when an executable named `node` (`node.exe` on Windows) is in a PATH entry. No shell involved. */
export function nodeOnPath(
  pathEnv: string | undefined,
  platform: NodeJS.Platform = process.platform,
  exists: (file: string) => boolean = existsSync,
): boolean {
  if (!pathEnv) return false;
  const sep = platform === 'win32' ? ';' : ':';
  const names = platform === 'win32' ? ['node.exe'] : ['node'];
  for (const raw of pathEnv.split(sep)) {
    const dir = raw.trim().replace(/^"(.*)"$/, '$1');
    if (!dir) continue;
    for (const n of names) {
      const candidate = platform === 'win32' ? `${dir.replace(/[\\/]+$/, '')}\\${n}` : path.posix.join(dir, n);
      if (exists(candidate)) return true;
    }
  }
  return false;
}

export interface McpConfigOptions {
  launcher: string;
  execPath: string;
  hasNode: boolean;
}

/** The `mcpServers` snippet for agents that read a mcp.json (Kiro, Cursor, Claude Code, ...). */
export function buildMcpConfig(o: McpConfigOptions): { mcpServers: { openboard: { command: string; args: string[]; env?: Record<string, string> } } } {
  const entry: { command: string; args: string[]; env?: Record<string, string> } = o.hasNode
    ? { command: 'node', args: [o.launcher] }
    : { command: o.execPath, args: [o.launcher], env: { ELECTRON_RUN_AS_NODE: '1' } };
  return { mcpServers: { openboard: entry } };
}
